(function () {
  const $ = (s, r = document) => r.querySelector(s);
  const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const yt = (id) => 'https://www.youtube.com/watch?v=' + id;
  const play = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M8 5v14l11-7z" fill="currentColor"/></svg>';

  function card(n, i) {
    return `<article class="ln-card reveal">
      <button class="ln-thumb" type="button" data-i="${i}" aria-label="Xem video ${esc(n.ten)}, ${n.video.dai}">
        <img src="assets/bia-video/${n.ma}.webp" alt="Khung hình video ${esc(n.ten)} ở ${esc(n.dia_danh)}" loading="lazy" width="480" height="270">
        <span class="ln-play">${play}</span><span class="ln-dur">${n.video.dai}</span>
      </button>
      <div class="ln-body">
        <span class="ln-place">${esc(n.dia_danh)}</span>
        <h3>${esc(n.ten)}</h3>
        <p>${esc(n.tom_tat)}</p>
        <button class="ln-more" type="button" data-i="${i}">Quy trình &amp; video →</button>
      </div>
      <img class="ln-qr" src="assets/qr/${n.ma}.png" alt="Mã QR video ${esc(n.ten)}" width="84" height="84">
    </article>`;
  }

  /* thứ tự 6 video ở mục «Trải nghiệm thực» (sếp chọn 30/10/2026) */
  const HIEN = ['xe-day', 'det-chieu', 'duc-nhom', 'lam-muoi', 'say-cau', 'ken-dong'];
  const shown = () => HIEN.map((m) => window.LANG_NGHE.find((n) => n.ma === m)).filter(Boolean);

  function render() {
    const grid = $('#ln-grid');
    if (!grid) return;
    const list = shown();
    grid.innerHTML = list.map(card).join('');
    if ($('#ln-count')) $('#ln-count').textContent = `${list.length} video học sinh thăm làng nghề truyền thống`;
    if ($('#ln-more-row')) $('#ln-more-row').innerHTML = window.HAI_HAU_THEM.map((v) =>
      `<a class="ln-mini" href="${yt(v.video.id)}" target="_blank" rel="noopener">
        <img src="assets/bia-video/${v.ma}.webp" alt="" loading="lazy" width="160" height="90"><span>${esc(v.ten)}<small>${v.video.dai} · YouTube</small></span></a>`).join('');
    grid.addEventListener('click', (e) => {
      const b = e.target.closest('[data-i]');
      if (b) open(+b.dataset.i);
    });
    if (window.IntersectionObserver) {
      const io = new IntersectionObserver((es) => es.forEach((x) => { if (x.isIntersecting) { x.target.classList.add('in'); io.unobserve(x.target); } }), { threshold: 0.12 });
      grid.querySelectorAll('.reveal').forEach((el) => io.observe(el));
    } else grid.querySelectorAll('.reveal').forEach((el) => el.classList.add('in'));
  }

  let cur = 0;
  function open(i) {
    const list = shown();
    cur = (i + list.length) % list.length;
    const n = list[cur], dlg = $('#ln-dialog');
    // YouTube cần biết trang nhúng ở đâu (Referer) — thiếu là báo «Error 153». Mở bằng bấm đúp index.html (file://) thì không có,
    // nên hiện ảnh bìa + nút mở YouTube; trang trên mạng (GitHub Pages) thì phát ngay trong khung.
    const web = /^https?:$/.test(location.protocol);
    $('#ln-frame').innerHTML = (web
      ? `<iframe src="https://www.youtube.com/embed/${n.video.id}?autoplay=1&rel=0&playsinline=1&origin=${encodeURIComponent(location.origin)}" title="Video ${esc(n.ten)}" allow="autoplay; encrypted-media; picture-in-picture; fullscreen" referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe>`
      : `<a class="ln-bia" href="${yt(n.video.id)}" target="_blank" rel="noopener"><img src="assets/bia-video/${n.ma}.webp" alt=""><span>▶ Xem video trên YouTube</span><small>Video mở trên YouTube; khi trang đưa lên mạng (GitHub Pages) video phát ngay trong khung</small></a>`) +
      `<button class="v-tg v-tg-l" type="button" id="ln-prev" aria-label="Nghề trước" title="Nghề trước"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M16 4.5v15L4.5 12z"/></svg></button>` +
      `<button class="v-tg v-tg-r" type="button" id="ln-next" aria-label="Nghề sau" title="Nghề sau"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M8 4.5v15L19.5 12z"/></svg></button>`;
    $('#ln-d-place').textContent = n.dia_danh + ', tỉnh Ninh Bình';
    $('#ln-d-title').textContent = n.ten;
    $('#ln-d-sum').textContent = n.tom_tat;
    $('#ln-d-steps').innerHTML = n.quy_trinh.map((s) => `<li>${esc(s)}</li>`).join('');
    $('#ln-d-chal').textContent = n.thach_thuc;
    const warn = [n.can_kiem ? 'Số liệu và quy trình nghề này viết từ lời trong video, đội đang kiểm lại.' : '', n.cho_xac_nhan ? 'Tên xã mới của làng này lấy theo nguồn phụ, đang đối chiếu văn bản sáp nhập.' : ''].filter(Boolean);
    $('#ln-d-warn').textContent = warn.join(' ');
    $('#ln-d-warn').hidden = !warn.length;
    $('#ln-d-src').innerHTML = ['Video thực địa — học sinh quay, kênh Hải Hậu 360'].concat(n.nguon).map((s) => `<li>${esc(s)}</li>`).join('');
    $('#ln-d-yt').href = yt(n.video.id);
    if (!dlg.open) { dlg.showModal(); document.body.classList.add('no-scroll'); }
  }
  function close() {
    const dlg = $('#ln-dialog');
    $('#ln-frame').innerHTML = '';
    if (dlg.open) dlg.close();
    document.body.classList.remove('no-scroll');
  }

  window.LN_OPEN = (ma) => { const i = shown().findIndex((n) => n.ma === ma); if (i >= 0) open(i); };

  document.addEventListener('DOMContentLoaded', () => {
    render();
    const dlg = $('#ln-dialog');
    if (!dlg) return;
    $('#ln-close').addEventListener('click', close);
    // nút tam giác nằm trong khung video (dựng lại mỗi lần mở) → bắt sự kiện ở khung
    $('#ln-frame').addEventListener('click', (e) => {
      if (e.target.closest('#ln-prev')) open(cur - 1);
      else if (e.target.closest('#ln-next')) open(cur + 1);
    });
    dlg.addEventListener('cancel', (e) => { e.preventDefault(); close(); });
    dlg.addEventListener('click', (e) => { if (e.target === dlg) close(); });
  });
})();
